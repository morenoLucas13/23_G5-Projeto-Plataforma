// Função para imprimir a questão
function imprimirQuestao(questao) {
    console.log(`ID: ${questao.id}`);
    console.log(`Texto da Questão: ${questao.textoQuestao}`);
    console.log(`Enunciado: ${questao.enunciado}`);
    console.log("Alternativas:");
    for (let [letra, texto] of Object.entries(questao.alternativas)) {
        console.log(`${letra}: ${texto}`);
    }
    console.log(`Resposta Correta: ${questao.respostaCorreta}`);
}

